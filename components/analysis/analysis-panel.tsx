import { Info, TriangleAlert } from "lucide-react";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { INTERPRETED_FIELDS, readStoredAnalysis, type StoredAnalysis } from "@/lib/analysis/schema";
import { formatDateTime } from "@/lib/format";
import type { AdAnalysisRow, AdLibraryRow } from "@/lib/supabase/types";
import { AcceptAngleButton } from "./accept-angle-button";
import { RunAnalysisButton } from "./run-analysis-button";

const NO_PERFORMANCE_NOTE =
  "Kuvah does not estimate spend, revenue, ROAS, conversions or reach. Nothing here describes how the ad performed.";

/** AI interpretation, test ideas and history for one ad. Stale runs arrive already marked failed. */
export function AnalysisPanel({ ad, analyses }: { ad: AdLibraryRow; analyses: AdAnalysisRow[] }) {
  const latest = analyses[0];
  const latestStatus = latest?.status ?? null;
  const shown = analyses.find((a) => a.status === "complete");
  const stored = shown ? readStoredAnalysis(shown.result) : null;

  return (
    <div className="flex flex-col gap-6">
      <Card>
        <CardHeader>
          <div className="flex flex-wrap items-center justify-between gap-2">
            <CardTitle>AI interpretation</CardTitle>
            <RunAnalysisButton adId={ad.id} hasRun={Boolean(latest)} />
          </div>
          <CardDescription>
            Generated by AI from the captured text{stored?.used_image ? " and uploaded image" : ""}. Treat it as a starting point, not
            fact.
          </CardDescription>
        </CardHeader>
        <CardContent className="flex flex-col gap-5">
          {latestStatus === "failed" ? (
            <Alert variant="destructive">
              <TriangleAlert aria-hidden />
              <AlertTitle>The latest analysis failed</AlertTitle>
              <AlertDescription>{latest?.error ?? "It did not finish. Run it again."}</AlertDescription>
            </Alert>
          ) : null}
          {latestStatus === "pending" ? (
            <Alert>
              <Info aria-hidden />
              <AlertDescription>An analysis is running. Refresh in a moment.</AlertDescription>
            </Alert>
          ) : null}

          {stored && shown ? (
            <AnalysisBody adId={ad.id} currentAngle={ad.marketing_angle} analysis={stored} run={shown} />
          ) : latestStatus !== "pending" ? (
            <p className="text-sm text-muted-foreground">
              No analysis yet. Run one to break down the hook, offer, audience, angle and structure.
            </p>
          ) : null}

          <p className="flex gap-2 rounded-md bg-muted/60 p-3 text-xs text-muted-foreground">
            <Info className="mt-0.5 size-3.5 shrink-0" aria-hidden />
            {NO_PERFORMANCE_NOTE}
          </p>
        </CardContent>
      </Card>

      {stored ? <IdeasCard analysis={stored} /> : null}
      {analyses.length ? <HistoryCard analyses={analyses} shownId={shown?.id ?? null} /> : null}
    </div>
  );
}

function AnalysisBody({ adId, currentAngle, analysis, run }: {
  adId: string;
  currentAngle: string | null;
  analysis: StoredAnalysis;
  run: AdAnalysisRow;
}) {
  const canAcceptAngle =
    analysis.angle_label && analysis.angle_label.toLowerCase() !== (currentAngle ?? "").toLowerCase();

  return (
    <>
      {run.warnings.length ? (
        <Alert>
          <TriangleAlert aria-hidden />
          <AlertTitle>Some AI output was removed</AlertTitle>
          <AlertDescription>
            <ul className="list-disc pl-4">
              {run.warnings.map((w) => (
                <li key={w}>{w}</li>
              ))}
            </ul>
          </AlertDescription>
        </Alert>
      ) : null}

      <dl className="flex flex-col gap-4">
        {INTERPRETED_FIELDS.map(([key, label]) => {
          const field = analysis.fields[key];
          return (
            <div key={key} className="flex flex-col gap-1">
              <dt className="flex items-center gap-2 text-sm font-medium">
                {label}
                <Badge variant="outline" className="font-normal">
                  Interpretation
                </Badge>
              </dt>
              <dd className={`text-sm ${field.withheld ? "text-muted-foreground italic" : ""}`}>
                {key === "marketing_angle" && analysis.angle_label ? <strong>{analysis.angle_label}: </strong> : null}
                {field.value}
                {field.supporting_quote ? (
                  <blockquote className="mt-1 border-l-2 pl-3 text-xs text-muted-foreground">
                    <span className="sr-only">Supporting quote from the captured ad: </span>“{field.supporting_quote}”
                  </blockquote>
                ) : null}
                {key === "marketing_angle" && canAcceptAngle ? (
                  <div className="mt-2">
                    <AcceptAngleButton adId={adId} label={analysis.angle_label!} />
                  </div>
                ) : null}
              </dd>
            </div>
          );
        })}
      </dl>

      {analysis.effectiveness_reasons.length ? (
        <section className="flex flex-col gap-2">
          <h3 className="flex items-center gap-2 text-sm font-medium">
            Why it might work
            <Badge variant="outline" className="font-normal">
              Hypotheses
            </Badge>
          </h3>
          <ul className="flex list-disc flex-col gap-1 pl-5 text-sm">
            {analysis.effectiveness_reasons.map((r, i) => (
              <li key={i}>
                {r.reason}
                {r.supporting_quote ? <span className="text-xs text-muted-foreground"> — “{r.supporting_quote}”</span> : null}
              </li>
            ))}
          </ul>
        </section>
      ) : null}

      {analysis.limitations.length ? (
        <section className="flex flex-col gap-1">
          <h3 className="text-sm font-medium">What the AI could not judge</h3>
          <ul className="list-disc pl-5 text-sm text-muted-foreground">
            {analysis.limitations.map((l, i) => (
              <li key={i}>{l}</li>
            ))}
          </ul>
        </section>
      ) : null}

      <p className="text-xs text-muted-foreground">
        {run.provider === "fake" ? "Offline test analyzer" : run.model} · {formatDateTime(run.completed_at ?? run.created_at)}
      </p>
    </>
  );
}

function IdeasCard({ analysis }: { analysis: StoredAnalysis }) {
  if (!analysis.test_ideas.length) return null;
  return (
    <Card>
      <CardHeader>
        <div className="flex items-center justify-between gap-2">
          <CardTitle>Ideas to test</CardTitle>
          <Badge variant="secondary">Original ideas</Badge>
        </div>
        <CardDescription>Directions inspired by the approach, not copies of the ad. Check any claims before using them.</CardDescription>
      </CardHeader>
      <CardContent>
        <ol className="flex list-decimal flex-col gap-3 pl-5 text-sm">
          {analysis.test_ideas.map((t, i) => (
            <li key={i}>
              <p className="font-medium">{t.idea}</p>
              <p className="text-muted-foreground">{t.rationale}</p>
            </li>
          ))}
        </ol>
      </CardContent>
    </Card>
  );
}

const STATUS_TEXT = { pending: "Running", complete: "Complete", failed: "Failed" } as const;

function HistoryCard({ analyses, shownId }: { analyses: AdAnalysisRow[]; shownId: string | null }) {
  return (
    <Card>
      <CardHeader>
        <CardTitle>Analysis history</CardTitle>
        <CardDescription>Every run is kept. The newest complete run is shown above.</CardDescription>
      </CardHeader>
      <CardContent>
        <ul className="flex flex-col gap-2 text-sm">
          {analyses.map((a) => {
            const status = a.status;
            return (
              <li key={a.id} className="flex flex-wrap items-center gap-2">
                <Badge variant={status === "failed" ? "destructive" : status === "complete" ? "default" : "secondary"}>
                  {STATUS_TEXT[status]}
                </Badge>
                <span>{formatDateTime(a.created_at)}</span>
                <span className="text-muted-foreground">{a.provider === "fake" ? "offline" : a.model}</span>
                {a.id === shownId ? <span className="text-xs text-muted-foreground">(shown)</span> : null}
                {status === "failed" && a.error ? <span className="w-full text-xs text-muted-foreground">{a.error}</span> : null}
              </li>
            );
          })}
        </ul>
      </CardContent>
    </Card>
  );
}
